package build

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"time"

	_jsii "github.com/michaelbomholt665/go-tree-sitter/internal/tree-sitter"
)

const ManifestSchemaVersion = 2

type Clock interface {
	Now() time.Time
}

type RealClock struct{}

func (RealClock) Now() time.Time { return time.Now() }

type ManifestData struct {
	SchemaVersion   int                `json:"schema_version"`
	Grammar         string             `json:"grammar"`
	Version         string             `json:"version"`
	CompiledAt      string             `json:"compiled_at"`
	TreeSitterVer   string             `json:"tree_sitter_version"`
	ParserABI       uint32             `json:"parser_abi"`
	Binaries        []BinaryInfo       `json:"binaries"`
	ABI             ABIInfo            `json:"abi"`
	Artifacts       ArtifactInfo       `json:"artifacts"`
	BuildProvenance []BinaryProvenance `json:"build_provenance"`
}

type BinaryInfo struct {
	Platform       string `json:"platform"`
	Arch           string `json:"arch"`
	Filename       string `json:"filename"`
	ChecksumSHA256 string `json:"checksum_sha256"`
}

type ABIInfo struct {
	MinVersion    uint32 `json:"min_version"`
	MaxVersion    uint32 `json:"max_version"`
	ParserVersion string `json:"parser_version"`
}

type ArtifactInfo struct {
	HasNodeTypes        bool `json:"has_node_types"`
	HasCompactNodeTypes bool `json:"has_compact_node_types"`
	HasQueries          bool `json:"has_queries"`
	HasWasm             bool `json:"has_wasm"`
	HasCSource          bool `json:"has_c_source"`
	HasJS               bool `json:"has_js"`
}

func GenerateManifest(lang _jsii.Language, binaryPaths []string, measuredABI map[string]uint32, provenance map[string]BinaryProvenance, artifacts ArtifactInfo) (*ManifestData, error) {
	if len(binaryPaths) == 0 {
		return nil, errors.New("cannot generate manifest without binaries")
	}
	binaries := make([]BinaryInfo, 0, len(binaryPaths))
	buildProvenance := make([]BinaryProvenance, 0, len(binaryPaths))
	var parserABI uint32
	var generatorVersion string
	var compiledEpoch int64
	for _, path := range binaryPaths {
		info, err := os.Lstat(path)
		if err != nil {
			return nil, fmt.Errorf("inspect final binary %q: %w", path, err)
		}
		if !info.Mode().IsRegular() {
			return nil, fmt.Errorf("final binary %q is not a regular file", path)
		}
		abi, ok := measuredABI[path]
		if !ok || abi == 0 {
			return nil, fmt.Errorf("final binary %q has no measured parser ABI", path)
		}
		if parserABI == 0 {
			parserABI = abi
		} else if parserABI != abi {
			return nil, fmt.Errorf("grammar %s binaries have different measured ABIs: %d and %d", lang.Name, parserABI, abi)
		}
		binaryProvenance, ok := provenance[path]
		if !ok {
			return nil, fmt.Errorf("final binary %q has no build provenance", path)
		}
		if binaryProvenance.Filename != filepath.Base(path) {
			return nil, fmt.Errorf("provenance filename %q does not match final binary %q", binaryProvenance.Filename, filepath.Base(path))
		}
		if generatorVersion == "" {
			generatorVersion = binaryProvenance.GeneratorVersion
		} else if generatorVersion != binaryProvenance.GeneratorVersion {
			return nil, fmt.Errorf("grammar %s binaries were generated by different Tree-sitter versions", lang.Name)
		}
		if binaryProvenance.SourceDateEpoch > compiledEpoch {
			compiledEpoch = binaryProvenance.SourceDateEpoch
		}
		checksum, err := checksumFile(path)
		if err != nil {
			return nil, err
		}
		filename := filepath.Base(path)
		platform, arch, err := parseBinaryMetadata(filename, lang)
		if err != nil {
			return nil, err
		}
		binaries = append(binaries, BinaryInfo{Platform: platform, Arch: arch, Filename: filename, ChecksumSHA256: checksum})
		buildProvenance = append(buildProvenance, binaryProvenance)
	}
	sort.Slice(binaries, func(i, j int) bool { return binaries[i].Filename < binaries[j].Filename })
	sort.Slice(buildProvenance, func(i, j int) bool { return buildProvenance[i].Filename < buildProvenance[j].Filename })
	return &ManifestData{
		SchemaVersion:   ManifestSchemaVersion,
		Grammar:         lang.Grammar,
		Version:         lang.Version,
		CompiledAt:      time.Unix(compiledEpoch, 0).UTC().Format(time.RFC3339),
		TreeSitterVer:   generatorVersion,
		ParserABI:       parserABI,
		Binaries:        binaries,
		ABI:             ABIInfo{MinVersion: parserABI, MaxVersion: parserABI, ParserVersion: generatorVersion},
		Artifacts:       artifacts,
		BuildProvenance: buildProvenance,
	}, nil
}

func (m *ManifestData) WriteToFile(outputPath string) error {
	if err := ValidateManifest(m, filepath.Dir(outputPath), nil); err != nil {
		return fmt.Errorf("validate manifest before writing: %w", err)
	}
	return writeJSONAtomic(outputPath, m)
}

// ValidateManifest checks schema invariants and final-byte checksums. When
// measuredABI is supplied it also binds the manifest to ABI measurements made
// from those exact native files.
func ValidateManifest(m *ManifestData, artifactDir string, measuredABI map[string]uint32) error {
	if m == nil {
		return errors.New("manifest is nil")
	}
	var validationErrors []error
	if m.SchemaVersion != ManifestSchemaVersion {
		validationErrors = append(validationErrors, fmt.Errorf("schema_version is %d, expected %d", m.SchemaVersion, ManifestSchemaVersion))
	}
	if m.ParserABI == 0 {
		validationErrors = append(validationErrors, errors.New("parser_abi must be a measured positive value"))
	}
	if m.ABI.MinVersion != m.ParserABI || m.ABI.MaxVersion != m.ParserABI {
		validationErrors = append(validationErrors, fmt.Errorf("legacy ABI bounds %d-%d must both equal parser_abi %d", m.ABI.MinVersion, m.ABI.MaxVersion, m.ParserABI))
	}
	if m.TreeSitterVer == "" || m.ABI.ParserVersion != m.TreeSitterVer {
		validationErrors = append(validationErrors, errors.New("legacy parser_version must equal measured tree_sitter_version"))
	}
	provenanceByFilename := make(map[string]BinaryProvenance, len(m.BuildProvenance))
	for _, provenance := range m.BuildProvenance {
		provenanceByFilename[provenance.Filename] = provenance
	}
	for _, binary := range m.Binaries {
		path := filepath.Join(artifactDir, binary.Filename)
		checksum, err := checksumFile(path)
		if err != nil {
			validationErrors = append(validationErrors, err)
			continue
		}
		if checksum != binary.ChecksumSHA256 {
			validationErrors = append(validationErrors, fmt.Errorf("checksum mismatch for %q: manifest %s, final bytes %s", path, binary.ChecksumSHA256, checksum))
		}
		if measuredABI != nil {
			if abi, ok := measuredABI[path]; !ok || abi != m.ParserABI {
				validationErrors = append(validationErrors, fmt.Errorf("parser ABI mismatch for %q: manifest %d, measured %d", path, m.ParserABI, abi))
			}
		}
		provenance, ok := provenanceByFilename[binary.Filename]
		if !ok {
			validationErrors = append(validationErrors, fmt.Errorf("missing build provenance for %q", binary.Filename))
			continue
		}
		if provenance.GeneratorVersion != m.TreeSitterVer {
			validationErrors = append(validationErrors, fmt.Errorf("generator version mismatch for %q: manifest %s, measured provenance %s", binary.Filename, m.TreeSitterVer, provenance.GeneratorVersion))
		}
	}
	if m.Artifacts.HasWasm && artifactDir != "" {
		wasmFile := filepath.Join(artifactDir, fmt.Sprintf("tree-sitter-%s.wasm", m.Grammar))
		wasmFileAlt := filepath.Join(artifactDir, fmt.Sprintf("tree-sitter-%s.wasm", filepath.Base(artifactDir)))
		_, err1 := os.Stat(wasmFile)
		_, err2 := os.Stat(wasmFileAlt)
		if err1 != nil && err2 != nil {
			validationErrors = append(validationErrors, fmt.Errorf("manifest declares has_wasm=true but wasm artifact missing in %s", artifactDir))
		}
	}
	if m.Artifacts.HasCSource && artifactDir != "" {
		parserC := filepath.Join(artifactDir, "src", "parser.c")
		if _, err := os.Stat(parserC); err != nil {
			validationErrors = append(validationErrors, fmt.Errorf("manifest declares has_c_source=true but %s missing: %w", parserC, err))
		}
	}
	if m.Artifacts.HasJS && artifactDir != "" {
		grammarJS := filepath.Join(artifactDir, "grammar.js")
		if _, err := os.Stat(grammarJS); err != nil {
			validationErrors = append(validationErrors, fmt.Errorf("manifest declares has_js=true but %s missing: %w", grammarJS, err))
		}
	}
	if m.Artifacts.HasCompactNodeTypes && artifactDir != "" {
		compactFile := filepath.Join(artifactDir, "compact-node-types.yaml")
		if _, err := os.Stat(compactFile); err != nil {
			validationErrors = append(validationErrors, fmt.Errorf("manifest declares has_compact_node_types=true but %s missing: %w", compactFile, err))
		}
	}
	return errors.Join(validationErrors...)
}

func CalculateChecksums(filePaths []string) (map[string]string, error) {
	checksums := make(map[string]string, len(filePaths))
	for _, path := range filePaths {
		checksum, err := checksumFile(path)
		if err != nil {
			return nil, err
		}
		checksums[path] = checksum
	}
	return checksums, nil
}

func parseBinaryMetadata(filename string, lang _jsii.Language) (string, string, error) {
	stem := filename[:len(filename)-len(filepath.Ext(filename))]
	prefix := fmt.Sprintf("%s-%s-", lang.Name, lang.Version)
	if len(stem) < len(prefix) || stem[:len(prefix)] != prefix {
		return "", "", fmt.Errorf("binary %q does not match expected prefix %q", filename, prefix)
	}
	parts := splitTargetSuffix(stem[len(prefix):])
	if len(parts) != 2 {
		return "", "", fmt.Errorf("binary %q does not match expected platform/arch naming", filename)
	}
	return parts[0], parts[1], nil
}

func splitTargetSuffix(value string) []string {
	for _, platform := range []string{"linux", "windows", "macos"} {
		prefix := platform + "-"
		if len(value) > len(prefix) && value[:len(prefix)] == prefix {
			return []string{platform, value[len(prefix):]}
		}
	}
	return nil
}
